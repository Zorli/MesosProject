package it.polimi.ingsoft.mesos.server.model.enums;

/**
 * Identifies the logical type of a tribe-deck card.
 */
public enum TribeCardType {
    /** Hunter character card. */
    HUNTER,
    /** Shaman character card. */
    SHAMAN,
    /** Artist character card. */
    ARTIST,
    /** Builder character card. */
    BUILDER,
    /** Inventor character card. */
    INVENTOR,
    /** Gatherer character card. */
    GATHERER,
    /** Event card drawn from the tribe deck. */
    EVENT
}
