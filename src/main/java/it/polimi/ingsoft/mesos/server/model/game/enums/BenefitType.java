package it.polimi.ingsoft.mesos.server.model.game.enums;

/**
 * Enumerates all building benefit categories supported by the model.
 *
 * <p>Each value identifies the rule family a building card belongs to, so scoring and event logic
 * can dispatch the correct effect implementation or lookup.
 */
public enum BenefitType {
    /** Rewards food when the tribe forms the required set after drawing. */
    POST_DRAW_SET_FOR_FOOD,                             // <-- done
    /** Rewards food when the tribe owns a matching pair of inventors. */
    POST_DRAW_PAIR_OF_INVENTOR_WITH_SAME_INVENTION,     // <-- done
    /** Grants an extra draw opportunity during the end-of-round sequence. */
    END_ROUND_EXTRA_CARD,                               // <-- TODO but we use it in the end round phase
    /** Modifies the totem position reached after returning to the starting tile. */
    END_ROUND_TOTEM_POSITION,                           // <-- TODO but we use it in the end round phase

    // We just have to call the applyEffect on the event cards and give them the player list.
    /** Reduces the sustenance penalty for a specific tribe-card type. */
    EVENT_BONUS_SUSTENANCE_DISCOUNT_FOR_TYPE,           // <-- done
    /** Prevents or mitigates the prestige-point loss from the shaman ritual event. */
    EVENT_BONUS_LOSS_FROM_SHAMAN_EVENT,                 // <-- done
    /** Doubles or boosts the reward of winning the shaman ritual event. */
    EVENT_BONUS_SHAMAN_WIN_MULTIPLIER,                  // <-- done
    /** Adds bonus stars to shamans during shaman-related event resolution. */
    EVENT_BONUS_STARS_SHAMAN,                           // <-- done
    /** Adds bonus food and prestige points during the hunt event. */
    EVENT_BONUS_HUNTER,                                 // <-- done
    /** Adds extra food during the cave painting event. */
    EVENT_BONUS_CAVE_PAINTING,                          // <-- done

    /** Awards prestige points during final scoring when the tribe completes a set. */
    FINAL_PRESTIGE_POINTS_FOR_SET,                      // <-- done
    /** Multiplies the final prestige points generated by builder cards. */
    BUILDER_TOTAL_PP_MULTIPLIER,                        // <-- done in tribe
    /** Multiplies the final bonus earned from a specific tribe-card type. */
    FINAL_BONUS_MULTIPLIER_FOR_TYPE,                    // <-- done
    /** Grants a large flat prestige-point reward during final scoring. */
    FINAL_BONUS_BIG_PP_REWARD,                          // <-- done

    /**
     *
     * All the increment for the final Phase of a Match:
     *
     * -- Bonus of the Buildings with FINAL EFFECT
     * idea: in the final phase of the match we check that if the player has a building with a FINAL...
     * we just call the applyEffect giving the player as parameter
     *
     * -- PrestigePoints of the buildings
     * In the final phase we also have to increase the pp of the Players just going through the players buildings calling BuildingCard.getPrestigePoints()
     *
     * -- Bonus of the Builders for final phase
     * Also in the final phase for each Player we have to call Player.gainPrestigePoints(Player.getTribe().getPrestigePointsForBuilderInFinalPhase())
     *
     */
}
