package it.polimi.ingsoft.mesos.server.model.game.enums;

/**
 * Enumerates all building benefit categories supported by the model.
 *
 * <p>Each value identifies the rule family a building card belongs to, so scoring and event logic
 * can dispatch the correct effect implementation or lookup.
 */
public enum BenefitType {
    /** Rewards food when the tribe forms the required set after drawing. */
    POST_DRAW_SET_FOR_FOOD,
    /** Rewards food when the tribe owns a matching pair of inventors. */
    POST_DRAW_PAIR_OF_INVENTOR_WITH_SAME_INVENTION,
    /** Grants an extra draw opportunity during the end-of-round sequence. */
    END_ROUND_EXTRA_CARD,
    /** Grants extra food when the player's totem is placed on a positive-food starting-tile block. */
    END_ROUND_TOTEM_POSITION,

    /** Reduces the sustenance penalty for a specific tribe-card type. */
    EVENT_BONUS_SUSTENANCE_DISCOUNT_FOR_TYPE,
    /** Prevents or mitigates the prestige-point loss from the shaman ritual event. */
    EVENT_BONUS_LOSS_FROM_SHAMAN_EVENT,
    /** Doubles or boosts the reward of winning the shaman ritual event. */
    EVENT_BONUS_SHAMAN_WIN_MULTIPLIER,
    /** Adds bonus stars to shamans during shaman-related event resolution. */
    EVENT_BONUS_STARS_SHAMAN,
    /** Adds bonus food and prestige points during the hunt event. */
    EVENT_BONUS_HUNTER,
    /** Adds extra food during the cave painting event. */
    EVENT_BONUS_CAVE_PAINTING,

    /** Awards prestige points during final scoring when the tribe completes a set. */
    FINAL_PRESTIGE_POINTS_FOR_SET,
    /** Multiplies the final prestige points generated by builder cards. */
    BUILDER_TOTAL_PP_MULTIPLIER,
    /** Multiplies the final bonus earned from a specific tribe-card type. */
    FINAL_BONUS_MULTIPLIER_FOR_TYPE,
    /** Grants a large flat prestige-point reward during final scoring. */
    FINAL_BONUS_BIG_PP_REWARD,
}
